create table if not exists public.byd_settings (
  user_id uuid primary key references auth.users(id) on delete cascade,
  gas_price numeric not null default 24,
  electric_price numeric not null default 5,
  charger_kw numeric not null default 0.95,
  updated_at timestamptz not null default now()
);
create table if not exists public.byd_trips (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  date date not null,
  odometer numeric,
  km_manual numeric,
  battery integer check (battery between 0 and 100),
  notes text,
  created_at timestamptz not null default now()
);
create table if not exists public.byd_charges (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  date date not null,
  odometer numeric,
  hours numeric,
  kwh_measured numeric,
  kwh numeric not null default 0,
  cost numeric not null default 0,
  battery_before integer check (battery_before between 0 and 100),
  battery_after integer check (battery_after between 0 and 100),
  notes text,
  created_at timestamptz not null default now()
);
create table if not exists public.byd_fuel (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  date date not null,
  odometer numeric,
  liters numeric not null,
  price numeric not null,
  cost numeric not null,
  full_tank boolean not null default false,
  notes text,
  created_at timestamptz not null default now()
);
alter table public.byd_settings enable row level security;
alter table public.byd_trips enable row level security;
alter table public.byd_charges enable row level security;
alter table public.byd_fuel enable row level security;
drop policy if exists "Users manage own settings" on public.byd_settings;
create policy "Users manage own settings" on public.byd_settings for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own trips" on public.byd_trips;
create policy "Users manage own trips" on public.byd_trips for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own charges" on public.byd_charges;
create policy "Users manage own charges" on public.byd_charges for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own fuel" on public.byd_fuel;
create policy "Users manage own fuel" on public.byd_fuel for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
